#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md: the license texts of everything linked
# into the slepok binary. Run before every release and after changing
# dependencies.
set -euo pipefail
cd "$(dirname "$0")/.."

out=THIRD_PARTY_NOTICES.md
self=$(go list -m)

go_license=$(go env GOROOT)/LICENSE
[[ -f $go_license ]] || go_license=/usr/share/licenses/go/LICENSE
[[ -f $go_license ]] || { echo "cannot find the Go license" >&2; exit 1; }

section() { # title file
    printf '## %s\n\n```\n' "$1"
    cat "$2"
    printf '```\n\n'
}

{
    printf '# Third-party notices\n\n'
    printf 'The slepok binary includes the following third-party software. This file\n'
    printf 'is generated by scripts/third_party_notices.sh.\n\n'
    printf 'Software inside snapshots is not covered here: each package keeps its own\n'
    printf 'license files, and every snapshot carries reports/NOTICE.txt.\n\n'
    section "Go standard library ($(go env GOVERSION))" "$go_license"

    # Every non-standard package linked into the binary, with the license
    # files of its own directory and of its module root.
    go list -deps -f '{{if not .Standard}}{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}} {{.Dir}}{{end}}' ./cmd/slepok |
        awk -v self="$self" '$1 != self' | sort -u |
        while read -r mod ver root dir; do
            for d in "$root" "$dir"; do
                find "$d" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) |
                    sed "s|^|$mod $ver $root |"
            done
        done | sort -u |
        while read -r mod ver root file; do
            section "$mod $ver — ${file#"$root"/}" "$file"
        done
} > "$out"

echo "wrote $out"
