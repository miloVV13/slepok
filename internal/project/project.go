// Package project reads and writes the files slepok keeps in a project:
// slepok.toml (written by people) and slepok.lock (written by slepok init).
package project

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"

	"github.com/BurntSushi/toml"

	"github.com/miloVV13/slepok/internal/manifest"
	"github.com/miloVV13/slepok/internal/profile"
	"github.com/miloVV13/slepok/internal/safepath"
)

const (
	ConfigName = "slepok.toml"
	LockName   = "slepok.lock"
	IgnoreName = ".slepokignore"
)

type Config struct {
	Profile string `toml:"profile"`
	Board   string `toml:"board"`
	// Platforms are the host platforms snapshots carry packages for.
	Platforms []string `toml:"platforms"`
	BuildDir  string   `toml:"build_dir"`
}

type Lock struct {
	Profile        string          `toml:"profile"`
	ProfileVersion string          `toml:"profile_version"`
	Packages       []LockedPackage `toml:"package"`
}

type LockedPackage struct {
	Name     string         `toml:"name"`
	Version  string         `toml:"version"`
	Platform string         `toml:"platform"`
	License  string         `toml:"license"`
	Source   profile.Source `toml:"source"`
}

type Project struct {
	Dir    string
	Config Config
	// Lock is nil until slepok init has written slepok.lock.
	Lock *Lock
}

// Find loads the project containing start: the nearest directory, start
// included, that has a slepok.toml.
func Find(start string) (*Project, error) {
	dir, err := filepath.Abs(start)
	if err != nil {
		return nil, err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, ConfigName)); err == nil {
			return Load(dir)
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return nil, fmt.Errorf("no %s in %s or any parent directory; run slepok init", ConfigName, start)
		}
		dir = parent
	}
}

// Load loads the project in dir.
func Load(dir string) (*Project, error) {
	p := &Project{Dir: dir}
	if err := decodeFile(filepath.Join(dir, ConfigName), &p.Config); err != nil {
		return nil, err
	}
	if err := p.Config.Validate(); err != nil {
		return nil, fmt.Errorf("%s: %w", ConfigName, err)
	}
	var lock Lock
	switch err := decodeFile(filepath.Join(dir, LockName), &lock); {
	case err == nil:
		p.Lock = &lock
	case !errors.Is(err, fs.ErrNotExist):
		return nil, err
	}
	return p, nil
}

// ReadLock reads the slepok.lock of the project in dir without validating
// slepok.toml, so that a broken configuration never hides which packages a
// project needs. It returns nil, nil when there is no lock.
func ReadLock(dir string) (*Lock, error) {
	var lock Lock
	err := decodeFile(filepath.Join(dir, LockName), &lock)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return &lock, nil
}

func decodeFile(p string, v any) error {
	data, err := os.ReadFile(p)
	if err != nil {
		return err
	}
	md, err := toml.Decode(string(data), v)
	if err != nil {
		return fmt.Errorf("%s: %w", filepath.Base(p), err)
	}
	if undecoded := md.Undecoded(); len(undecoded) > 0 {
		return fmt.Errorf("%s: unknown keys %v", filepath.Base(p), undecoded)
	}
	return nil
}

// Validate checks the configuration against the profile it names.
func (c *Config) Validate() error {
	prof, err := profile.Load(c.Profile)
	if err != nil {
		return err
	}
	if !slices.Contains(prof.Boards, c.Board) {
		return fmt.Errorf("board %q is not supported by profile %s (supported: %v)", c.Board, c.Profile, prof.Boards)
	}
	if len(c.Platforms) == 0 {
		return fmt.Errorf("platforms must list at least one platform, e.g. [%q]", manifest.HostPlatform())
	}
	if err := safepath.Check(c.BuildDir); err != nil {
		return fmt.Errorf("build_dir: %w", err)
	}
	return nil
}

// BuildDir returns the absolute build directory.
func (p *Project) BuildDir() string {
	return filepath.Join(p.Dir, filepath.FromSlash(p.Config.BuildDir))
}

// PackagesFor returns the locked packages usable on platform.
func (l *Lock) PackagesFor(platform string) []LockedPackage {
	var out []LockedPackage
	for _, pkg := range l.Packages {
		if pkg.Platform == platform || pkg.Platform == manifest.AnyPlatform {
			out = append(out, pkg)
		}
	}
	return out
}

const configHeader = `# Slepok project configuration. See https://github.com/miloVV13/slepok
`

// WriteConfig writes slepok.toml into dir.
func WriteConfig(dir string, c Config) error {
	var buf bytes.Buffer
	buf.WriteString(configHeader)
	if err := toml.NewEncoder(&buf).Encode(c); err != nil {
		return err
	}
	return writeAtomic(filepath.Join(dir, ConfigName), buf.Bytes())
}

const lockHeader = `# Generated by slepok init. Commit this file: it pins the exact build
# environment of the project.
`

// WriteLock writes slepok.lock into dir.
func WriteLock(dir string, l Lock) error {
	var buf bytes.Buffer
	buf.WriteString(lockHeader)
	if err := toml.NewEncoder(&buf).Encode(l); err != nil {
		return err
	}
	return writeAtomic(filepath.Join(dir, LockName), buf.Bytes())
}

func writeAtomic(p string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(p), "."+filepath.Base(p)+".tmp-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), p)
}
